/** Document sharing with need-to-know access, through the real UI. Server on E2E_BASE after `seed_demo --reset`. */
import { createRequire } from 'module'
import fs from 'fs'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const BASE = process.env.E2E_BASE || 'http://127.0.0.1:8000'
const PASSWORD = 'Tuliwamu#Demo2026'
const FIX = new URL('./fixtures/', import.meta.url).pathname
const SHOTS = new URL('./screenshots/', import.meta.url).pathname
fs.mkdirSync(SHOTS, { recursive: true })
const ok = (m) => console.log('  ✓', m)
const browser = await chromium.launch()
async function as(username) {
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true })).newPage()
  page.on('pageerror', (e) => console.error('PAGE ERROR', e.message))
  await page.goto(`${BASE}/login`)
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Password').fill(PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL(/\/app/)
  return page
}
async function openIncoming(page, ref) {
  await page.goto(`${BASE}/app/referrals?direction=incoming`)
  await page.getByRole('row', { name: new RegExp(ref) }).getByRole('link').click()
  await page.getByText('Purpose').first().waitFor()
}

console.log('1. Police register a case and make a medical referral')
const police = await as('police.officer')
await police.goto(`${BASE}/app/cases/new`)
await police.getByLabel('Pseudonym').fill('Demo Child Docs')
await police.getByLabel('Age range').selectOption('9-11')
await police.getByLabel('General incident category').selectOption('PHYSICAL_VIOLENCE')
await police.getByLabel('District').fill('Kampala')
await police.getByRole('button', { name: 'Register case' }).click()
await police.locator('h1', { hasText: 'TLW-' }).waitFor()
const caseUrl = police.url().split('?')[0]
const ref = (await police.locator('h1').innerText()).trim()
await police.getByRole('button', { name: 'Make referral' }).first().click()
await police.getByLabel('Referral type').selectOption('MEDICAL')
await police.getByLabel('Receiving institution').selectOption({ label: 'Nakawa Demo Referral Hospital — Kampala' })
await police.getByLabel('Purpose and what you are asking for').fill('Examination; please send the report.')
await police.getByRole('button', { name: 'Send referral' }).click()
await police.getByText('Sent — awaiting acknowledgement').first().waitFor()
ok(`case ${ref} with medical referral`)

console.log('2. Hospital completes the referral and attaches the medical report')
const medic = await as('medical.officer')
await openIncoming(medic, ref)
await medic.getByRole('button', { name: 'Acknowledge' }).click()
await medic.getByText('Acknowledged', { exact: true }).first().waitFor()
await medic.getByRole('button', { name: 'Record completion' }).click()
await medic.getByLabel(/Completion summary/).fill('Examined; report attached.')
await medic.locator('#' + (await medic.getByText('Choose a file (PDF, photo or Word)').locator('..').getAttribute('for'))).setInputFiles(`${FIX}medical-report-demo.pdf`)
await medic.getByRole('button', { name: 'Confirm' }).click()
await medic.getByText('medical-report-demo.pdf', { exact: true }).first().waitFor()
await medic.getByText(/Shared with: Kampala Central Police Station/).waitFor()
ok('medical report uploaded and shared with the referring police station only')
await medic.screenshot({ path: `${SHOTS}d1-hospital-report.png`, fullPage: true })

console.log('3. Police download the report, send the case file to the ODPP and forward the medical report')
await police.goto(caseUrl + '?tab=documents')
await police.getByText('medical-report-demo.pdf', { exact: true }).first().waitFor()
const dl = police.waitForEvent('download')
await police.getByRole('button', { name: 'Download' }).first().click()
const file = await (await dl).path()
if (!fs.readFileSync(file).subarray(0, 5).equals(Buffer.from('%PDF-'))) throw new Error('download is not the PDF')
ok('police downloaded the medical report')
await police.goto(caseUrl)
await police.getByRole('button', { name: 'Make referral' }).first().click()
await police.getByLabel('Referral type').selectOption('PROSECUTION')
await police.getByLabel('Receiving institution').selectOption({ index: 1 })
await police.getByLabel('Purpose and what you are asking for').fill('Police file for prosecution review.')
await police.locator('#referral-attach').setInputFiles(`${FIX}police-file-demo.pdf`)
await police.getByRole('button', { name: 'Send referral' }).click()
await police.getByText('Prosecution review (ODPP)').first().waitFor()
ok('police file sent with the ODPP referral')
await police.goto(caseUrl + '?tab=documents')
const medRow = police.locator('li', { hasText: 'medical-report-demo.pdf' })
await medRow.getByRole('button', { name: 'Forward' }).click()
await police.getByLabel('Send to').selectOption({ label: 'ODPP Demonstration Office – Kampala' })
await police.getByRole('dialog').getByRole('button', { name: 'Forward' }).click()
await police.waitForTimeout(800)
await police.screenshot({ path: `${SHOTS}d2-police-documents.png`, fullPage: true })
ok('medical report forwarded to the ODPP')

console.log('4. Prosecutor sees both documents on the referral; hospital never sees the police file')
const pros = await as('prosecutor')
await openIncoming(pros, ref)
await pros.getByText('police-file-demo.pdf', { exact: true }).waitFor()
await pros.getByText('medical-report-demo.pdf', { exact: true }).waitFor()
await pros.screenshot({ path: `${SHOTS}d3-prosecutor-documents.png`, fullPage: true })
ok('prosecutor has the police file and the forwarded medical report')
await medic.goto(`${BASE}/app/referrals?direction=incoming`)
await openIncoming(medic, ref)
if (await medic.getByText('police-file-demo.pdf').count()) throw new Error('hospital can see the police file')
ok('hospital cannot see the police file')
for (const u of ['court.registry', 'probation.officer', 'gulu.officer']) {
  const p = await as(u)
  await p.goto(caseUrl + '?tab=documents')
  await p.waitForTimeout(1500)
  if (await p.getByText(/medical-report-demo|police-file-demo/).count()) throw new Error(`${u} can see documents`)
}
ok('court, probation and another police station see nothing')
await browser.close()
console.log('\nDocument flow passed.')
